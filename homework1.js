null + 3;
// null в математиці стає 0. 0 + 3 = 3. Результат -  3

5 && "qwerty";
// && шукає перше хибне значення, а якщо такого немає - повертає останнє. 5 правдиве, "qwerty" теж правдиве, тому виводиться останнє. Результат: qwerty


+'40' + +'2' + "hillel";
// Плюс перед рядком робить з нього число: 40 і 2. 40 + 2 = 42. Далі 42 + "hillel" - тут вже стрінга, тому склеюється. Результат: 42hillel


'10' - 5 === 6;
// Мінус завжди рахує як числа, тому '10' стає 10. 10 - 5 = 5.
// Потім 5 === 6 - це неправда. Результат: false

true + false;
// true це 1, а false це 0. 1 + 0 = 1. Результат 1

'4px' - 3;
