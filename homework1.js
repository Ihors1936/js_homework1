'4' - 3;
// Мінус рахує як числа, '4' стає 4. 4 - 3 = 1. Результат: 1

'6' + 3 ** 0;
// Спочатку виконується степінь: 3 в степені 0 = 1. Потім '6' + 1 - це рядок плюс число, тому склеюється. Результат: 61

12 / '6';
// Ділення теж рахує як числа, '6' стає 6. 12 / 6 = 2. Результат: 2

'10' + (5 === 6);
